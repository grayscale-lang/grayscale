package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/spf13/cobra"
)

// completionSite is where one shell's completion script is written: the
// script's full path, and whether a missing directory may be made.
type completionSite struct {
	file            string
	createDirectory bool
}

// detectCompletionShell names the user's shell from the environment, or ""
// when it is not one of bash, zsh, fish, or powershell.
func detectCompletionShell(goos string, getenv func(string) string) string {
	if goos == "windows" {
		return "powershell"
	}
	switch filepath.Base(getenv("SHELL")) {
	case "bash", "zsh", "fish":
		return filepath.Base(getenv("SHELL"))
	}
	return ""
}

// completionSiteFor picks the script path for shell. zshFpath lists the
// directories on zsh's fpath; the first writable one is used, since zsh has
// no user directory it loads everywhere. ok is false when no directory fits.
func completionSiteFor(shell, home string, getenv func(string) string, zshFpath func() []string) (site completionSite, ok bool) {
	switch shell {
	case "fish":
		base := getenv("XDG_CONFIG_HOME")
		if base == "" {
			base = filepath.Join(home, ".config")
		}
		return completionSite{filepath.Join(base, "fish", "completions", "gray.fish"), true}, true
	case "bash":
		base := getenv("XDG_DATA_HOME")
		if base == "" {
			base = filepath.Join(home, ".local", "share")
		}
		return completionSite{filepath.Join(base, "bash-completion", "completions", "gray"), true}, true
	case "powershell":
		return completionSite{filepath.Join(home, ".gray", "completions", "gray.ps1"), true}, true
	case "zsh":
		for _, directory := range zshFpath() {
			if isWritableDirectory(directory) {
				return completionSite{filepath.Join(directory, "_gray"), false}, true
			}
		}
	}
	return completionSite{}, false
}

// isWritableDirectory reports whether a file can be created in directory.
func isWritableDirectory(directory string) bool {
	info, err := os.Stat(directory)
	if err != nil || !info.IsDir() {
		return false
	}
	probe, err := os.CreateTemp(directory, ".gray-completion-*")
	if err != nil {
		return false
	}
	probe.Close()
	os.Remove(probe.Name())
	return true
}

// queryZshFpath asks a non-interactive zsh for its fpath.
func queryZshFpath() []string {
	output, err := exec.Command("zsh", "-c", "print -l -- $fpath").Output()
	if err != nil {
		return nil
	}
	return strings.Fields(string(output))
}

// completionHint is the one line printed when the script was not installed.
func completionHint(shell string) string {
	switch shell {
	case "zsh":
		return "add `source <(gray completion zsh)` to ~/.zshrc"
	case "bash":
		return "add `source <(gray completion bash)` to ~/.bashrc"
	case "fish":
		return "run `gray completion fish > ~/.config/fish/completions/gray.fish`"
	case "powershell":
		return "add `gray completion powershell | Out-String | Invoke-Expression` to your profile"
	}
	return "run `gray completion <bash|zsh|fish|powershell>` and load the output"
}

// completionInstalledLine is the line printed once the script is written.
// PowerShell loads no directory on its own, so it names the profile line too.
func completionInstalledLine(shell, path string) string {
	if shell == "powershell" {
		return fmt.Sprintf("Shell completion written to %s; add `. \"%s\"` to your profile to load it", path, path)
	}
	return "Shell completion installed: " + path
}

// writeFileIfChanged writes content to path, creating its directory when
// asked, and leaves an identical file untouched.
func writeFileIfChanged(path string, content []byte, createDirectory bool) error {
	if existing, err := os.ReadFile(path); err == nil && bytes.Equal(existing, content) {
		return nil
	}
	if createDirectory {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
	}
	return os.WriteFile(path, content, 0o644)
}

// placeCompletionScript writes the script generate returns for shell to its
// site and returns the path, or "" when there is nowhere to write it or the
// write fails.
func placeCompletionScript(shell, home string, getenv func(string) string, zshFpath func() []string, generate func(shell string) ([]byte, error)) string {
	site, ok := completionSiteFor(shell, home, getenv, zshFpath)
	if !ok {
		return ""
	}
	script, err := generate(shell)
	if err != nil || len(script) == 0 || writeFileIfChanged(site.file, script, site.createDirectory) != nil {
		return ""
	}
	return site.file
}

// installCompletionScript writes the completion script generated by the gray
// binary at binaryPath into the directory the user's shell reads. It never
// fails the caller: when the shell, directory, or write is unavailable it
// prints one line with the command to run instead. No rc file is touched.
func installCompletionScript(binaryPath string) {
	// Under sudo the user's home is not the home that was meant.
	if os.Getenv("SUDO_USER") != "" {
		return
	}
	shell := detectCompletionShell(runtime.GOOS, os.Getenv)
	home, err := os.UserHomeDir()
	if shell != "" && err == nil {
		generate := func(shell string) ([]byte, error) {
			return exec.Command(binaryPath, "completion", shell).Output()
		}
		if path := placeCompletionScript(shell, home, os.Getenv, queryZshFpath, generate); path != "" {
			fmt.Println(completionInstalledLine(shell, path))
			return
		}
	}
	fmt.Printf("Shell completion not installed: %s\n", completionHint(shell))
}

var completionInstallCmd = &cobra.Command{
	Use:   "install",
	Short: "Install the completion script for your shell",
	Long: "Install the completion script for the shell named by $SHELL " +
		"(PowerShell on Windows) into the directory that shell loads.\n\n" +
		"No rc file is modified.",
	Args: cobra.NoArgs,
	Run: func(cmd *cobra.Command, args []string) {
		if binaryPath, err := os.Executable(); err == nil {
			installCompletionScript(binaryPath)
		}
	},
}
